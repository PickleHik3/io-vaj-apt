def _sha256_file(path):
    return gen._hash_file(path, "sha256")


def _selected_package_tuples(entries):
    return [
        (entry.name, entry.version, entry.arch, entry.sha256, entry.object_path, entry.size)
        for entry in entries
    ]


def _selected_package_tuples_from_provenance(provenance):
    tuples = []
    for record in provenance.get("selected_packages", []):
        tuples.append(
            (
                record.get("name"),
                record.get("version"),
                record.get("arch"),
                record.get("sha256"),
                record.get("object_path"),
                record.get("size"),
            )
        )
    return tuples


def _provenance_path(metadata_root):
    return os.path.join(metadata_root, PROVENANCE_REL_PATH)


def _canonical_metadata_paths(metadata_root):
    return {
        "Packages": os.path.join(
            metadata_root,
            "dists",
            SUITE,
            COMPONENT,
            ARCHITECTURE,
            "Packages",
        ),
        "Packages.gz": os.path.join(
            metadata_root,
            "dists",
            SUITE,
            COMPONENT,
            ARCHITECTURE,
            "Packages.gz",
        ),
        "Release": os.path.join(metadata_root, "dists", SUITE, "Release"),
    }


def _read_json(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def _validate_inrelease_matches_release(metadata_root):
    inrelease_path = os.path.join(metadata_root, "dists", SUITE, "InRelease")
    release_path = os.path.join(metadata_root, "dists", SUITE, "Release")
    if not os.path.isfile(inrelease_path):
        return
    if not os.path.isfile(release_path):
        raise RuntimeError("InRelease exists but Release is missing")
    with open(inrelease_path, "r", encoding="utf-8") as handle:
        inrelease_text = handle.read()
    start_marker = "\n\n"
    end_marker = "\n-----BEGIN PGP SIGNATURE-----\n"
    if not inrelease_text.startswith("-----BEGIN PGP SIGNED MESSAGE-----\n"):
        raise RuntimeError("InRelease is not a clearsigned Release file")
    if start_marker not in inrelease_text or end_marker not in inrelease_text:
        raise RuntimeError("InRelease is malformed and cannot be matched to Release")
    signed_body = inrelease_text.split(start_marker, 1)[1].split(end_marker, 1)[0]
    signed_body = signed_body.replace("\n- -", "\n-")
    with open(release_path, "r", encoding="utf-8") as handle:
        release_text = handle.read()
    if signed_body != release_text:
        raise RuntimeError("InRelease payload does not match Release")


def validate_metadata_provenance(repo_root, manifest_path, metadata_root):
    repo_root = Path(repo_root).resolve()
    manifest_path = Path(manifest_path).resolve()
    metadata_root = Path(metadata_root).resolve()
    manifest_entries = gen.load_manifest(manifest_path)
    provenance_path = metadata_root / PROVENANCE_REL_PATH
    if not provenance_path.is_file():
        raise RuntimeError(f"shared-generator provenance missing: {provenance_path}")

    provenance = _read_json(provenance_path)
    if provenance.get("schema_version") != gen.PROVENANCE_SCHEMA_VERSION:
        raise RuntimeError("provenance schema version mismatch")

    generator = provenance.get("generator", {})
    expected_generator = gen.generator_identity(repo_root)
    if generator != expected_generator:
        raise RuntimeError("provenance generator identity mismatch")

    manifest_record = provenance.get("manifest", {})
    manifest_rel = manifest_path.relative_to(repo_root).as_posix()
    if manifest_record.get("path") != manifest_rel:
        raise RuntimeError("provenance manifest path mismatch")
    if manifest_record.get("sha256") != gen.manifest_digest(manifest_path):
        raise RuntimeError("provenance manifest digest mismatch")
    if manifest_record.get("selected_package_count") != len(manifest_entries):
        raise RuntimeError("provenance package count mismatch")

    expected_packages = _selected_package_tuples(manifest_entries)
    actual_packages = _selected_package_tuples_from_provenance(provenance)
    if len(actual_packages) != len(set(actual_packages)):
        raise RuntimeError("provenance contains duplicate selected package records")
    if actual_packages != expected_packages:
        raise RuntimeError("provenance selected package set mismatch")

    release_generation = provenance.get("release_generation", {})
    if not release_generation.get("release_generated_by_shared_generator"):
        raise RuntimeError("provenance does not attest to shared-generator Release output")
    release_time_text = release_generation.get("release_time_utc")
    if not isinstance(release_time_text, str):
        raise RuntimeError("provenance release timestamp missing")
    release_time = gen._parse_release_time(release_time_text)

    artifact_paths = {
        name: Path(path)
        for name, path in _canonical_metadata_paths(metadata_root).items()
    }
    artifacts = provenance.get("artifacts", {})
    for artifact_name, artifact_path in artifact_paths.items():
        if not artifact_path.is_file():
            raise RuntimeError(f"canonical metadata missing: {artifact_name}")
        record = artifacts.get(artifact_name)
        if not isinstance(record, dict):
            raise RuntimeError(f"provenance missing artifact record for {artifact_name}")
        artifact_rel = artifact_path.relative_to(metadata_root).as_posix()
        if record.get("path") != artifact_rel:
            raise RuntimeError(f"provenance path mismatch for {artifact_name}")
        actual_size = artifact_path.stat().st_size
        if record.get("size") != actual_size:
            raise RuntimeError(f"provenance size mismatch for {artifact_name}")
        actual_sha = _sha256_file(artifact_path)
        if record.get("sha256") != actual_sha:
            raise RuntimeError(f"provenance digest mismatch for {artifact_name}")

    with tempfile.TemporaryDirectory(prefix="vaj-provenance-") as temp_root:
        regenerated = gen.generate_repository(
            manifest_path,
            repo_root,
            Path(temp_root),
            release_time=release_time,
        )
        for artifact_name, regen_path in (
            ("Packages", regenerated["packages_path"]),
            ("Packages.gz", regenerated["packages_gz_path"]),
            ("Release", regenerated["release_path"]),
            ("Provenance", regenerated["provenance_path"]),
        ):
            if artifact_name == "Provenance":
                current_path = provenance_path
            else:
                current_path = artifact_paths[artifact_name]
            with open(current_path, "rb") as current_handle, open(regen_path, "rb") as regen_handle:
                if current_handle.read() != regen_handle.read():
                    raise RuntimeError(f"{artifact_name} does not match shared-generator output")

    _validate_inrelease_matches_release(metadata_root)
    packages_stanzas = [
        stanza
        for stanza in artifact_paths["Packages"].read_text(encoding="utf-8").strip().split("\n\n")
        if stanza.strip()
    ]
    if len(packages_stanzas) != len(manifest_entries):
        raise RuntimeError("Packages stanza count mismatch")

    return {
        "manifest_sha256": manifest_record["sha256"],
        "package_count": len(manifest_entries),
        "provenance_path": provenance_path,
        "packages_path": artifact_paths["Packages"],
    }


def sign(key, msg):
    return hmac.new(key, msg.encode("utf-8"), hashlib.sha256).digest()


def get_signature_key(secret, date, region, service):
    kDate = sign(("AWS4" + secret).encode("utf-8"), date)
    kRegion = sign(kDate, region)
    kService = sign(kRegion, service)
    return sign(kService, "aws4_request")


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def s3_put(bucket, key, endpoint, region, access_key, secret_key, data, content_type, cache_control=None, _retries=4):
    import time
    for attempt in range(_retries + 1):
        status = _s3_put_once(bucket, key, endpoint, region, access_key, secret_key, data, content_type, cache_control)
        if status in (200, 201):
            return status
        if attempt < _retries:
            wait = 2 ** attempt
            print(f"  PUT {key}: got {status}, retrying in {wait}s (attempt {attempt+1}/{_retries})...", file=sys.stderr)
            time.sleep(wait)
    return status


def _s3_put_once(bucket, key, endpoint, region, access_key, secret_key, data, content_type, cache_control=None):
    service = "s3"
    encoded_bucket = quote(bucket, safe="")
    encoded_key = quote(key, safe="/~")
    url = f"{endpoint}/{encoded_bucket}/{encoded_key}"
    t = datetime.datetime.now(datetime.UTC)
    amzdate = t.strftime("%Y%m%dT%H%M%SZ")
    datestamp = t.strftime("%Y%m%d")
    payload_hash = sha256(data)
    host_part = endpoint.replace("https://", "")
    headers = {
        "Host": host_part,
        "X-Amz-Date": amzdate,
        "X-Amz-Content-SHA256": payload_hash,
        "Content-Type": content_type,
    }
    if cache_control is not None:
        headers["Cache-Control"] = cache_control
    signed_headers = ";".join(sorted(k.lower() for k in headers))
    canonical_headers = "".join(
        f"{k.lower()}:{v}\n"
        for k, v in sorted(headers.items(), key=lambda x: x[0].lower())
    )
    canonical_uri = f"/{encoded_bucket}/{encoded_key}"
    canonical_request = (
        f"PUT\n{canonical_uri}\n\n{canonical_headers}\n{signed_headers}\n{payload_hash}"
    )
    credential_scope = f"{datestamp}/{region}/{service}/aws4_request"
    string_to_sign = (
        f"AWS4-HMAC-SHA256\n{amzdate}\n{credential_scope}\n"
        + sha256(canonical_request.encode("utf-8"))
    )
    signing_key = get_signature_key(secret_key, datestamp, region, service)
    signature = hmac.new(
        signing_key, string_to_sign.encode("utf-8"), hashlib.sha256
    ).hexdigest()
    authorization = (
        f"AWS4-HMAC-SHA256 Credential={access_key}/{credential_scope}, "
        f"SignedHeaders={signed_headers}, Signature={signature}"
    )
    headers["Authorization"] = authorization
    req = urllib.request.Request(url, data=data, headers=headers, method="PUT")
    try:
        resp = urllib.request.urlopen(req, timeout=60)
        return resp.status
    except urllib.error.HTTPError as e:
        return e.code
    except urllib.error.URLError:
        return 0


