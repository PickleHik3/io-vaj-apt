#!/usr/bin/env python3
"""publish-r2.py — Upload repository files to Cloudflare R2 via S3 API.

Reads AWS/R2 credentials from environment. Uses allowlist from foundation
manifest (manifests/foundation.tsv) to permit only certified files.

Usage:
    source ~/.config/vaj-apt/r2.env
    python3 scripts/publish-r2.py [file ...] | --all \
        | --verify \
        | --refresh-metadata-cache-policy [--dry-run]
"""

import argparse, gzip, hashlib, hmac, datetime, importlib.util, json, os, socket, sys, tempfile, urllib.request, urllib.error
from pathlib import Path
from urllib.parse import quote

# Cloudflare R2 S3 endpoints always publish A (IPv4) records. Some hosts
# (notably WSL2) have broken IPv6 egress to Cloudflare that does not fail fast
# but hangs each request until the socket timeout (~60s), then retries -- so a
# publish stalls for many minutes instead of erroring. Force IPv4 resolution
# unless a future IPv6-only host explicitly opts out with PUBLISH_R2_ALLOW_IPV6.
if not os.environ.get("PUBLISH_R2_ALLOW_IPV6"):
    _orig_getaddrinfo = socket.getaddrinfo

    def _ipv4_only_getaddrinfo(host, port, family=0, *args, **kwargs):
        return _orig_getaddrinfo(host, port, socket.AF_INET, *args, **kwargs)

    socket.getaddrinfo = _ipv4_only_getaddrinfo

MANIFEST_PATH = "manifests/foundation.tsv"
_GENERATOR_MODULE_PATH = os.path.join(os.path.dirname(__file__), "generate_repo.py")
_GENERATOR_SPEC = importlib.util.spec_from_file_location("vaj_generate_repo", _GENERATOR_MODULE_PATH)
gen = importlib.util.module_from_spec(_GENERATOR_SPEC)
sys.modules[_GENERATOR_SPEC.name] = gen
_GENERATOR_SPEC.loader.exec_module(gen)

SUITE = "stable"
COMPONENT = "main"
ARCHITECTURE = "binary-aarch64"
PROVENANCE_REL_PATH = f"dists/{SUITE}/{gen.PROVENANCE_FILENAME}"

MUTABLE_METADATA = frozenset([
    f"dists/{SUITE}/InRelease",
    f"dists/{SUITE}/Release",
    f"dists/{SUITE}/Release.gpg",
    f"dists/{SUITE}/{COMPONENT}/{ARCHITECTURE}/Packages",
    f"dists/{SUITE}/{COMPONENT}/{ARCHITECTURE}/Packages.gz",
])

MUTABLE_CACHE_CONTROL = "max-age=0, must-revalidate"


def load_allowlist(repo_root):
    """Load allowed object paths from the foundation manifest."""
    manifest = os.path.join(repo_root, MANIFEST_PATH)
    allowed = set()
    if os.path.exists(manifest):
        with open(manifest) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) >= 5:
                    allowed.add(parts[4])
    # Also allow metadata and key files
    allowed.add(f"dists/{SUITE}/Release")
    allowed.add(f"dists/{SUITE}/Release.gpg")
    allowed.add(f"dists/{SUITE}/InRelease")
    allowed.add(f"dists/{SUITE}/{COMPONENT}/{ARCHITECTURE}/Packages")
    allowed.add(f"dists/{SUITE}/{COMPONENT}/{ARCHITECTURE}/Packages.gz")
    allowed.add(PROVENANCE_REL_PATH)
    allowed.add("keys/io-vaj-archive.gpg")
    allowed.add("keys/io-vaj-archive.asc")
    return allowed


def _parse_args(argv):
    parser = argparse.ArgumentParser(
        description="Publish VAJ APT repository content to Cloudflare R2.",
    )
    parser.add_argument(
        "files",
        nargs="*",
        help="relative repository paths to upload, or omit when using a mode flag",
    )
    parser.add_argument("--all", action="store_true", help="upload the manifest allowlist")
    parser.add_argument("--verify", action="store_true", help="verify mutable metadata cache policy")
    parser.add_argument(
        "--refresh-metadata-cache-policy",
        action="store_true",
        help="re-upload only mutable metadata with the canonical Cache-Control header",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print refresh-metadata actions without uploading",
    )
    parser.add_argument(
        "--validate-provenance",
        action="store_true",
        help="validate that local metadata was generated by the shared manifest-authoritative generator",
    )
    parser.add_argument(
        "--repo-root",
        help="override the repository root used for manifest and pool validation",
    )
    parser.add_argument(
        "--manifest",
        help="override the active manifest path used for provenance validation",
    )
    parser.add_argument(
        "--metadata-root",
        help="override the metadata tree root used for provenance validation",
    )
    args = parser.parse_args(argv)
    modes = sum(
        bool(flag)
        for flag in (
            args.all,
            args.verify,
            args.refresh_metadata_cache_policy,
            args.validate_provenance,
        )
    )
    if modes > 1:
        parser.error("choose only one mode flag from --all, --verify, --refresh-metadata-cache-policy, --validate-provenance")
    if args.dry_run and not args.refresh_metadata_cache_policy:
        parser.error("--dry-run is only valid with --refresh-metadata-cache-policy")
    if args.files and modes:
        parser.error("positional file uploads cannot be combined with a mode flag")
    if not args.files and not modes:
        parser.error("provide file paths or one mode flag")
    return args


